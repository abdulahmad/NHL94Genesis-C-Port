#!/usr/bin/env python3
"""Writes native/cardcolor_faces.inc: the hash of each of the cartridge's 144 player pictures (Card001 ...
Card144, in ROM order), so the game can find a card's colour face by its number. Only numbers go in.

    python3 tools/cardcolor_faces.py nhl94retail.bin > native/cardcolor_faces.inc

The pictures follow each other from Card001 (0xC75D6 in the retail ROM): a picture is 8 header bytes
(its map's offset at +4, 0 for the common 6 x 6 map), the tile count word and 24 bytes a tile, then its
own map when it has one (the width and height words and 36 entries). hash: FNV-1a (32 bits) of the
count word and the tiles, as tools/cardcolor_table.py's.
"""
import sys

FIRST = 0xC75D6
CARDS = 144


def fnv(b):
    h = 0x811C9DC5
    for x in b:
        h = ((h ^ x) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    rom = open(sys.argv[1], "rb").read()
    out = ["/* Generated by tools/cardcolor_faces.py: hash of each card's tiles, CardNNN (the colour faces' numbers). */"]
    o = FIRST
    for k in range(1, CARDS + 1):
        n = int.from_bytes(rom[o + 8:o + 10], "big")
        mo = int.from_bytes(rom[o + 4:o + 8], "big")
        if not 0 < n <= 36:
            sys.exit("Card%03d at %X: not a picture" % (k, o))
        out.append("0x%08Xu,   /* Card%03d */" % (fnv(rom[o + 8:o + 10 + n * 24]), k))
        o += mo + 4 + 72 if mo else 8 + 2 + n * 24
    print("\n".join(out))


if __name__ == "__main__":
    main()
