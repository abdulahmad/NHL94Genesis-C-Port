#!/usr/bin/env python3
"""Writes native/cardcolor_table.inc, the colour player photos' table (native/cardcolor.c), from the
alignment the prototype found (a JSON list, one entry a card: card, player, hash, src "pc95"/"pc94",
file, tag, flip, h, a, oy, ox, check). Only numbers go in the table: which portrait of the player's own
PC game is the card's photo, and where it sits. No picture, no colour.

    python3 tools/cardcolor_table.py table.json > native/cardcolor_table.inc

hash is FNV-1a (32 bits) of the card's tile data in the ROM: the tile count word at the picture + 8,
then 24 bytes a tile.
"""
import json
import sys


def main():
    rows = json.load(open(sys.argv[1]))
    out = ["/* Generated by tools/cardcolor_table.py: the cards that have the same photo in NHL 95 PC or NHL 94 PC.",
           " * hash of the card's tiles, source, PORTRnnn.QFS (95 PC), portrait, mirrored, height, top, left, width.",
           " * \"check\": the match is less sure (Abdul looked at these on the sheets). */"]
    for r in sorted(rows, key=lambda r: r["card"]):
        src = "CC_PC95" if r["src"] == "pc95" else "CC_PC94"
        note = " (check)" if r.get("check") else ""
        out.append('{ 0x%08Xu, %s, %d, "%s", %d, %d, %d, %d, %r },   /* %s %s%s */'
                   % (r["hash"], src, r["file"], r["tag"], r["flip"], r["h"], r["oy"], r["ox"], r["a"],
                      r["card"], r["player"], note))
    print("\n".join(out))


if __name__ == "__main__":
    main()
