#!/usr/bin/env python3
"""Generate C arrays for data tables that live inside asm routines (local labels), so the port
does not transcribe them by hand. usage: gen_tables.py FILE.asm LABEL[:cname] ... -o OUT.h
A table runs from its label to the next label or instruction. Current 94G save-odds tables
use the PIX macro (one byte per 4-digit argument); ram94.asm equates are resolved to numbers
so committed array values stay."""
import re, sys, pathlib
args = sys.argv[1:]
src = pathlib.Path(args[0]); out = pathlib.Path(args[args.index('-o') + 1]); names = args[1:args.index('-o')]
lines = src.read_text(errors='replace').splitlines()
res = ['/* Generated by tools/gen_tables.py from %s. Do not edit. */' % src.name, '#pragma once', '#include <stdint.h>', '']

raw_eq = {}
for path in (src.parent / 'ram94.asm', src):
    if not path.exists():
        continue
    for line in path.read_text(errors='replace').splitlines():
        m = re.match(r'^([A-Za-z_]\w*)\s+equ\s+(\S+)', line.split(';')[0])
        if m:
            raw_eq[m.group(1)] = m.group(2)

def pix1(n):
    n = int(n)
    return str(((n // 1000) << 6) + (((n // 100) % 10) << 4) + (((n // 10) % 10) << 2) + (n % 10))

def resolve_name(tok, seen=None):
    seen = seen or set()
    if tok in seen:
        return None
    seen.add(tok)
    val = raw_eq.get(tok)
    if val is None:
        return None
    if re.match(r'^\$[0-9A-Fa-f]+$', val):
        return int(val[1:], 16)
    if re.match(r'^-\$[0-9A-Fa-f]+$', val):
        return -int(val[2:], 16)
    if re.match(r'^-?\d+$', val):
        return int(val)
    if val in raw_eq:
        return resolve_name(val, seen)
    return None

def eval_tok(tok):
    n = resolve_name(tok)
    if n is not None:
        return str(n & 0xFFFF if n < 0 else n)
    names = re.findall(r'[A-Za-z_]\w*', tok)
    if not names or all(resolve_name(n) is None for n in names):
        return tok
    def repl(m):
        v = resolve_name(m.group(0))
        if v is None:
            raise ValueError(m.group(0))
        return str(v)
    py = re.sub(r'[A-Za-z_]\w*', repl, tok)
    v = int(eval(py, {"__builtins__": {}}))
    return str(v & 0xFFFF if v < 0 else v)

for spec in names:
    label, _, cname = spec.partition(':'); cname = cname or label.lstrip('.')
    # find the label (local labels are unique within their routine; take the first after an optional routine prefix "routine/label")
    routine, _, lab = label.rpartition('/')
    start = None; in_routine = routine == ''
    for i, l in enumerate(lines):
        if routine and re.match(r'^' + re.escape(routine) + r'\b', l): in_routine = True
        if in_routine and re.match(r'^' + re.escape(lab) + r'\b', l): start = i; break
    if start is None: sys.exit(f'{label} not found')
    width, vals = None, []
    for l in lines[start:]:
        body = l.split(';')[0]
        if l is not lines[start] and re.match(r'^[A-Za-z_.]\w*', body): break   # next label ends the table
        pix = re.search(r'\bpix\s+(.*)', body, re.I)
        if pix:
            width = width or 'b'
            vals += [pix1(t) for t in re.findall(r'\d+', pix.group(1))]
            continue
        m = re.search(r'\bdc\.([bwl])\s+(.*)', body)
        if not m:
            if l is lines[start]: continue
            if body.strip() == '': continue
            break
        width = width or m.group(1)
        for tok in re.findall(r"'[^']*'|[^,\s]+", m.group(2)):
            if tok.startswith("'"): vals += [str(ord(c)) for c in tok[1:-1]]
            elif tok.startswith('$'): vals.append(str(int(tok[1:], 16)))
            elif tok.startswith('-$'): vals.append(str(-int(tok[2:], 16) & 0xFFFF))   # negative hex, as the word it assembles to
            elif re.match(r'^-?\d+$', tok): vals.append(tok)
            else: vals.append(eval_tok(tok))   # ram equate, runspeed expr, or SPA constant
    ct = {'b': 'uint8_t', 'w': 'uint16_t', 'l': 'uint32_t'}[width]
    res.append(f'static const {ct} {cname}[{len(vals)}] = {{ {", ".join(vals)} }};')
    print(f'{cname}: {len(vals)} x {ct}')
out.write_text('\n'.join(res) + '\n')
